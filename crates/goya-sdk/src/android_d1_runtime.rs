//! Kotlin emitter for the bounded scalar D1 runtime.
//!
//! The emitter validates through strict GY-LANG admission and the canonical
//! D1 compiler before producing standalone Kotlin. The generated class owns
//! one state map and applies each action as a checked, atomic transition.

use goya_lang::{
    CellKind, InteractionClass, InteractionExpr, InteractionType, InteractionValue, SourceRange,
};
use std::{error::Error, fmt};

/// Kotlin source plus origins for each generated D1 action branch.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AndroidD1Runtime {
    pub kotlin: String,
    pub source_digest: [u8; 32],
    pub action_ranges: Vec<(String, SourceRange)>,
}

/// Why a scene could not be emitted as a Kotlin D1 runtime.
#[derive(Debug)]
pub enum AndroidD1RuntimeError {
    StrictParse(goya_lang::StrictParseError),
    InvalidD1(goya_lang::TransitionError),
    Unsupported(&'static str),
    InvalidClassName,
}

impl fmt::Display for AndroidD1RuntimeError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{self:?}")
    }
}
impl Error for AndroidD1RuntimeError {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            Self::StrictParse(e) => Some(e),
            Self::InvalidD1(e) => Some(e),
            _ => None,
        }
    }
}

/// Emit the standalone runtime using the default Kotlin class name.
pub fn emit_android_d1_runtime(source: &str) -> Result<String, AndroidD1RuntimeError> {
    emit_android_d1_runtime_mapped(source, "GoyaD1Runtime").map(|runtime| runtime.kotlin)
}

/// Emit a source-mapped Kotlin runtime. State and input values are the three
/// canonical D1 scalar types; arithmetic is checked signed 64-bit addition.
pub fn emit_android_d1_runtime_mapped(
    source: &str,
    class_name: &str,
) -> Result<AndroidD1Runtime, AndroidD1RuntimeError> {
    if !super::is_kotlin_class_name(class_name) {
        return Err(AndroidD1RuntimeError::InvalidClassName);
    }
    let handoff = goya_lang::handoff::admit(source).map_err(AndroidD1RuntimeError::StrictParse)?;
    let scene = &handoff.parsed.scene;
    if scene.interactions.is_empty() {
        return Err(AndroidD1RuntimeError::Unsupported(
            "scenes without D1 actions",
        ));
    }
    if scene.interactions.iter().any(|i| {
        i.class != InteractionClass::D1 || !i.declared_effects.is_empty() || !i.requests.is_empty()
    }) {
        return Err(AndroidD1RuntimeError::Unsupported(
            "D2 or effectful interactions",
        ));
    }
    let compiled =
        goya_lang::compile_d1_interactions(scene).map_err(AndroidD1RuntimeError::InvalidD1)?;
    if compiled.len() != scene.interactions.len() {
        return Err(AndroidD1RuntimeError::Unsupported(
            "an incomplete D1 compilation",
        ));
    }

    let mut state_types = std::collections::BTreeMap::<String, InteractionType>::new();
    for interaction in &scene.interactions {
        if interaction.authored_id.as_deref().is_none_or(str::is_empty) {
            return Err(AndroidD1RuntimeError::Unsupported(
                "actions without authored IDs",
            ));
        }
        for key in interaction
            .state_reads
            .iter()
            .chain(&interaction.state_writes)
        {
            if state_types
                .insert(key.name.clone(), key.value_type)
                .is_some_and(|old| old != key.value_type)
            {
                return Err(AndroidD1RuntimeError::Unsupported(
                    "conflicting state types",
                ));
            }
        }
    }
    if state_types.len() > 256 {
        return Err(AndroidD1RuntimeError::Unsupported(
            "more than 256 application state keys",
        ));
    }
    let action_ranges = scene
        .interactions
        .iter()
        .map(|i| {
            let id = i
                .authored_id
                .as_ref()
                .ok_or(AndroidD1RuntimeError::Unsupported(
                    "actions without authored IDs",
                ))?;
            handoff
                .parsed
                .entries
                .iter()
                .find(|e| e.kind == "interaction" && e.semantic_id.as_deref() == Some(id.as_str()))
                .map(|e| (id.clone(), e.range))
                .ok_or(AndroidD1RuntimeError::Unsupported(
                    "actions without source origins",
                ))
        })
        .collect::<Result<Vec<_>, _>>()?;

    let mut out = String::new();
    out.push_str("/** Generated by Goya's canonical D1 compiler. */\n");
    out.push_str(&format!("class {class_name}(initialState: Map<String, {class_name}.Value>, initialRevision: ULong = 0uL) {{\n"));
    out.push_str("    sealed class Value { data class IntValue(val value: Long) : Value(); data class TextValue(val value: String) : Value(); data class BoolValue(val value: Boolean) : Value() }\n");
    out.push_str("    enum class ErrorCode { UNKNOWN_ACTION, INPUT_SCHEMA, INPUT_TYPE, STATE_SCHEMA, STATE_TYPE, INVALID_TEXT, TEXT_LIMIT, SNAPSHOT_LIMIT, REGISTER_LIMIT, ARITHMETIC_OVERFLOW, REVISION_OVERFLOW }\n");
    out.push_str("    data class Snapshot(val revision: ULong, val state: Map<String, Value>)\n    sealed class DispatchResult { data class Success(val revision: ULong) : DispatchResult(); data class Failure(val code: ErrorCode) : DispatchResult() }\n");
    out.push_str("    private val stateTypes: Map<String, String> = mapOf(");
    for (n, (key, ty)) in state_types.iter().enumerate() {
        if n > 0 {
            out.push_str(", ");
        }
        out.push_str(&format!(
            "{} to {}",
            kotlin_string(key),
            kotlin_string(type_name(*ty))
        ));
    }
    out.push_str(")\n    val requiredStateTypes: Map<String, String> get() = stateTypes.toMap()\n");
    out.push_str("    private var values: Map<String, Value>\n    @get:Synchronized var revision: ULong = initialRevision\n        private set\n    @get:Synchronized val state: Map<String, Value> get() = values.toMap()\n    @Synchronized fun snapshot(): Snapshot = Snapshot(revision, values.toMap())\n");
    out.push_str("    init { if (initialState.keys != stateTypes.keys) throw IllegalArgumentException(\"STATE_SCHEMA\"); if (!validMap(initialState) || mapSize(initialState) > MAX_SNAPSHOT_BYTES) throw IllegalArgumentException(\"SNAPSHOT_LIMIT\"); if (initialState.any { (k, v) -> kind(v) != stateTypes[k] }) throw IllegalArgumentException(\"STATE_TYPE\"); values = initialState.toMap() }\n");
    out.push_str("    @Synchronized fun dispatch(actionId: String, inputs: Map<String, Value>): DispatchResult {\n        return when (actionId) {\n");
    for i in &scene.interactions {
        let id = i
            .authored_id
            .as_ref()
            .ok_or(AndroidD1RuntimeError::Unsupported(
                "actions without authored IDs",
            ))?;
        out.push_str(&format!("            {} -> {{\n", kotlin_string(id)));
        let input_types = i
            .inputs
            .iter()
            .map(|k| (k.name.as_str(), k.value_type))
            .collect::<std::collections::BTreeMap<_, _>>();
        out.push_str("                if (inputs.keys != setOf(");
        for (n, key) in input_types.keys().enumerate() {
            if n > 0 {
                out.push_str(", ");
            }
            out.push_str(&kotlin_string(key));
        }
        out.push_str(")) return DispatchResult.Failure(ErrorCode.INPUT_SCHEMA)\n");
        out.push_str("                if (!validUnicode(inputs)) return DispatchResult.Failure(ErrorCode.INVALID_TEXT)\n                if (!withinTextLimit(inputs)) return DispatchResult.Failure(ErrorCode.TEXT_LIMIT)\n");
        for (key, ty) in &input_types {
            out.push_str(&format!("                if (kind(inputs[{}]!!) != {}) return DispatchResult.Failure(ErrorCode.INPUT_TYPE)\n", kotlin_string(key), kotlin_string(type_name(*ty))));
        }
        let touched = i
            .state_reads
            .iter()
            .chain(&i.state_writes)
            .map(|k| k.name.as_str())
            .collect::<std::collections::BTreeSet<_>>();
        for key in &touched {
            out.push_str(&format!("                val s_{} = values[{}] ?: return DispatchResult.Failure(ErrorCode.STATE_SCHEMA)\n", safe_ident(key), kotlin_string(key)));
        }
        out.push_str("                val snapshot = mapOf(");
        for (n, key) in touched.iter().enumerate() {
            if n > 0 {
                out.push_str(", ");
            }
            out.push_str(&format!("{} to s_{}", kotlin_string(key), safe_ident(key)));
        }
        out.push_str(")\n                if (mapSize(snapshot) + mapSize(inputs) > MAX_SNAPSHOT_BYTES) return DispatchResult.Failure(ErrorCode.SNAPSHOT_LIMIT)\n");
        let mut reg = 0usize;
        let mut statements = String::new();
        let mut assigned = Vec::new();
        for assignment in &i.assignments {
            let (name, _) = emit_expr(&assignment.value, &mut reg, &mut statements);
            assigned.push((assignment.key.as_str(), name));
        }
        if reg > 0 {
            out.push_str("                var registerBytes = 0\n");
        }
        out.push_str(&statements);
        out.push_str("                val next = values.toMutableMap()\n");
        for (key, value) in assigned {
            out.push_str(&format!(
                "                next[{}] = {}\n",
                kotlin_string(key),
                value
            ));
        }
        out.push_str("                if (!validMap(next) || mapSize(next) > MAX_SNAPSHOT_BYTES) return DispatchResult.Failure(ErrorCode.SNAPSHOT_LIMIT)\n                if (revision == ULong.MAX_VALUE) return DispatchResult.Failure(ErrorCode.REVISION_OVERFLOW)\n                val nextRevision = revision + 1uL\n                values = next.toMap()\n                revision = nextRevision\n                DispatchResult.Success(revision)\n            }\n");
    }
    out.push_str(
        "            else -> DispatchResult.Failure(ErrorCode.UNKNOWN_ACTION)\n        }\n    }\n",
    );
    out.push_str("    private fun kind(v: Value): String = when (v) { is Value.IntValue -> \"int\"; is Value.TextValue -> \"text\"; is Value.BoolValue -> \"bool\" }\n");
    out.push_str("    private fun validUnicode(m: Map<String, Value>): Boolean = m.values.none { it is Value.TextValue && !wellFormedUtf16(it.value) }\n    private fun withinTextLimit(m: Map<String, Value>): Boolean = m.values.all { it !is Value.TextValue || it.value.toByteArray(Charsets.UTF_8).size <= MAX_TEXT_BYTES }\n    private fun validMap(m: Map<String, Value>): Boolean = validUnicode(m) && withinTextLimit(m)\n");
    out.push_str("    private fun wellFormedUtf16(s: String): Boolean { var i = 0; while (i < s.length) { val c = s[i++]; if (c in '\\uD800'..'\\uDBFF') { if (i >= s.length || s[i] !in '\\uDC00'..'\\uDFFF') return false; i++ } else if (c in '\\uDC00'..'\\uDFFF') return false }; return true }\n");
    out.push_str("    private fun valueSize(v: Value): Int = when (v) { is Value.IntValue -> 8; is Value.TextValue -> v.value.toByteArray(Charsets.UTF_8).size; is Value.BoolValue -> 1 }\n");
    out.push_str("    private fun mapSize(m: Map<String, Value>): Int = 8 + m.entries.sumOf { (k, v) -> 8 + k.toByteArray(Charsets.UTF_8).size + valueSize(v) }\n");
    out.push_str("    private fun registerCost(n: String, v: Value): Int = n.toByteArray(Charsets.UTF_8).size + valueSize(v)\n");
    out.push_str("    private fun checkedAdd(a: Value, b: Value): Value.IntValue { val x = (a as? Value.IntValue)?.value ?: throw IllegalStateException(\"TYPE\"); val y = (b as? Value.IntValue)?.value ?: throw IllegalStateException(\"TYPE\"); if ((y > 0L && x > Long.MAX_VALUE - y) || (y < 0L && x < Long.MIN_VALUE - y)) throw ArithmeticException(\"overflow\"); return Value.IntValue(x + y) }\n");
    out.push_str("    companion object { const val MAX_SNAPSHOT_BYTES = 1048576; const val MAX_TEXT_BYTES = 65536; const val MAX_REGISTER_BYTES = 1048576 }\n}\n");
    Ok(AndroidD1Runtime {
        kotlin: out,
        source_digest: handoff.parsed.source_digest,
        action_ranges,
    })
}

fn emit_expr(
    expr: &InteractionExpr,
    next: &mut usize,
    out: &mut String,
) -> (String, InteractionType) {
    match expr {
        InteractionExpr::Literal(v) => {
            let dst = alloc_register(next);
            let (literal, ty) = match v {
                InteractionValue::Int(n) => (
                    format!("Value.IntValue({})", kotlin_i64(*n)),
                    InteractionType::Int,
                ),
                InteractionValue::Text(s) => (
                    format!("Value.TextValue({})", kotlin_string(s)),
                    InteractionType::Text,
                ),
                InteractionValue::Bool(b) => {
                    (format!("Value.BoolValue({b})"), InteractionType::Bool)
                }
            };
            out.push_str(&format!("                val {dst}: Value = {literal}\n"));
            emit_register_budget(&dst, out);
            (dst, ty)
        }
        InteractionExpr::State(key) => {
            let dst = alloc_register(next);
            out.push_str(&format!(
                "                val {dst}: Value = s_{}\n",
                safe_ident(key)
            ));
            emit_register_budget(&dst, out);
            (dst, InteractionType::Int)
        }
        InteractionExpr::Input(key) => {
            let dst = alloc_register(next);
            out.push_str(&format!(
                "                val {dst}: Value = inputs[{}]!!\n",
                kotlin_string(key)
            ));
            emit_register_budget(&dst, out);
            (dst, InteractionType::Int)
        }
        InteractionExpr::Add(a, b) => {
            let (left, _) = emit_expr(a, next, out);
            let (right, _) = emit_expr(b, next, out);
            let dst = alloc_register(next);
            out.push_str(&format!("                val {dst}: Value = try {{ checkedAdd({left}, {right}) }} catch (_: ArithmeticException) {{ return DispatchResult.Failure(ErrorCode.ARITHMETIC_OVERFLOW) }} catch (_: IllegalStateException) {{ return DispatchResult.Failure(ErrorCode.STATE_TYPE) }}\n"));
            emit_register_budget(&dst, out);
            (dst, InteractionType::Int)
        }
        InteractionExpr::Effect(_) => unreachable!("canonical D1 admission excludes effects"),
    }
}

fn alloc_register(next: &mut usize) -> String {
    let name = format!("r{}", *next);
    *next += 1;
    name
}
fn kotlin_i64(value: i64) -> String {
    if value == i64::MIN {
        "Long.MIN_VALUE".into()
    } else {
        format!("{value}L")
    }
}

fn emit_register_budget(name: &str, out: &mut String) {
    out.push_str(&format!("                registerBytes += registerCost({name:?}, {name})\n                if (registerBytes > MAX_REGISTER_BYTES) return DispatchResult.Failure(ErrorCode.REGISTER_LIMIT)\n"));
}

fn type_name(ty: InteractionType) -> &'static str {
    match ty {
        InteractionType::Int => "int",
        InteractionType::Text => "text",
        InteractionType::Bool => "bool",
    }
}
fn safe_ident(key: &str) -> String {
    let mut out = String::from("k_");
    for b in key.as_bytes() {
        out.push_str(&format!("{b:02x}"));
    }
    out
}
fn kotlin_string(value: &str) -> String {
    let mut out = String::from("\"");
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '$' => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() || !c.is_ascii() => {
                for u in c.encode_utf16(&mut [0; 2]).iter() {
                    out.push_str(&format!("\\u{u:04x}"));
                }
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
