//! Typed Kotlin source writer and the Aragon Android source map.
//!
//! [`KotlinWriter`] only accepts fixed code fragments as `&'static str`;
//! every value that comes from a scene (strings, numbers, colors) goes
//! through a typed method that renders a valid Kotlin literal. Values written
//! inside [`KotlinWriter::mapped`] are recorded against a GSSH/2 [`Origin`],
//! which becomes an entry of the [`AndroidSourceMap`].

use goya_lang::handoff::{Origin, SemanticHandoffV2};
use goya_lang::SourceRange;
use std::fmt;

/// Identifier of the source-map format written by [`AndroidSourceMap::to_json`].
pub const ANDROID_SOURCE_MAP_CONTRACT: &str = "ARAGON-SOURCE-MAP/1";

/// One generated Kotlin file, named relative to the package directory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KotlinFile {
    pub name: String,
    pub text: String,
}

/// A generated byte range and the authored construct it was produced from.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SourceMapEntry {
    pub file: String,
    /// Half-open UTF-8 byte range in the generated file.
    pub generated: SourceRange,
    pub origin: Origin,
    /// Half-open UTF-8 byte range of `origin` in the source revision.
    pub source: SourceRange,
}

/// Generated Kotlin → GSSH/2 origin map for one source revision.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AndroidSourceMap {
    pub source_digest: [u8; 32],
    /// Sorted by file, then generated start, then generated end.
    pub entries: Vec<SourceMapEntry>,
}

/// Why a source map does not describe a source and its generated files.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SourceMapError {
    /// The source is not admitted by GSSH/2.
    Admission(goya_lang::StrictParseError),
    /// The source digest differs from the one the map was generated for.
    DigestMismatch,
    /// An entry names a file that was not supplied.
    MissingFile(String),
    /// A generated range is out of bounds or not on UTF-8 boundaries.
    InvalidGeneratedRange(usize),
    /// An entry's origin does not resolve to its recorded source range.
    OriginMismatch(usize),
}

impl fmt::Display for SourceMapError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Admission(error) => write!(f, "source is not admitted: {error}"),
            Self::DigestMismatch => f.write_str("source digest does not match the map"),
            Self::MissingFile(name) => write!(f, "generated file {name} is missing"),
            Self::InvalidGeneratedRange(index) => {
                write!(f, "entry {index} has an invalid generated range")
            }
            Self::OriginMismatch(index) => {
                write!(f, "entry {index} no longer resolves to its source range")
            }
        }
    }
}

impl std::error::Error for SourceMapError {}

impl AndroidSourceMap {
    /// The innermost entry whose generated range contains `offset` in `file`.
    /// Use it to map a Kotlin compiler or runtime location back to source.
    pub fn lookup(&self, file: &str, offset: usize) -> Option<&SourceMapEntry> {
        self.entries
            .iter()
            .filter(|entry| {
                entry.file == file
                    && entry.generated.start <= offset
                    && offset < entry.generated.end
            })
            .min_by_key(|entry| entry.generated.end - entry.generated.start)
    }

    /// Check that the map belongs to `source` and `files`: same digest, every
    /// generated range in bounds and on character boundaries, and every
    /// origin still resolving to its recorded source range.
    pub fn verify(&self, source: &str, files: &[KotlinFile]) -> Result<(), SourceMapError> {
        let handoff = goya_lang::handoff::admit_v2(source).map_err(SourceMapError::Admission)?;
        if handoff.parsed().source_digest != self.source_digest {
            return Err(SourceMapError::DigestMismatch);
        }
        for (index, entry) in self.entries.iter().enumerate() {
            let file = files
                .iter()
                .find(|file| file.name == entry.file)
                .ok_or_else(|| SourceMapError::MissingFile(entry.file.clone()))?;
            let range = entry.generated;
            if range.start > range.end
                || range.end > file.text.len()
                || !file.text.is_char_boundary(range.start)
                || !file.text.is_char_boundary(range.end)
            {
                return Err(SourceMapError::InvalidGeneratedRange(index));
            }
            if handoff.origin(&entry.origin) != Some(entry.source) {
                return Err(SourceMapError::OriginMismatch(index));
            }
        }
        Ok(())
    }

    /// Deterministic JSON rendering (no whitespace variation, no timestamps).
    pub fn to_json(&self) -> String {
        let mut out = String::new();
        out.push_str("{\"contract\":");
        json_string(&mut out, ANDROID_SOURCE_MAP_CONTRACT);
        out.push_str(",\"source_sha256\":\"");
        for byte in self.source_digest {
            out.push_str(&format!("{byte:02x}"));
        }
        out.push_str("\",\"entries\":[");
        for (index, entry) in self.entries.iter().enumerate() {
            if index > 0 {
                out.push(',');
            }
            out.push_str("\n{\"file\":");
            json_string(&mut out, &entry.file);
            out.push_str(&format!(
                ",\"generated\":[{},{}],\"source\":[{},{}],\"origin\":",
                entry.generated.start, entry.generated.end, entry.source.start, entry.source.end
            ));
            json_origin(&mut out, &entry.origin);
            out.push('}');
        }
        out.push_str("\n]}\n");
        out
    }
}

fn json_origin(out: &mut String, origin: &Origin) {
    let fields: Vec<(&str, &str)> = match origin {
        Origin::Element(id) => vec![("kind", "element"), ("element", id)],
        Origin::Property { element, property } => vec![
            ("kind", "property"),
            ("element", element),
            ("property", property),
        ],
        Origin::Interaction(id) => vec![("kind", "interaction"), ("interaction", id)],
        Origin::State(key) => vec![("kind", "state"), ("state", key)],
        Origin::Binding { interaction, input } => vec![
            ("kind", "binding"),
            ("interaction", interaction),
            ("input", input),
        ],
    };
    out.push('{');
    for (index, (name, value)) in fields.into_iter().enumerate() {
        if index > 0 {
            out.push(',');
        }
        json_string(out, name);
        out.push(':');
        json_string(out, value);
    }
    out.push('}');
}

fn json_string(out: &mut String, value: &str) {
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
}

/// Render `value` as a Kotlin string literal. Non-ASCII and control
/// characters are written as UTF-16 `\u` escapes; `$` is escaped so the
/// literal never interpolates.
pub fn kotlin_string(value: &str) -> String {
    let mut out = String::from("\"");
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '$' => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() || !c.is_ascii() => {
                for unit in c.encode_utf16(&mut [0; 2]).iter() {
                    out.push_str(&format!("\\u{unit:04x}"));
                }
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// ASCII Kotlin identifier that is not a hard keyword.
pub(crate) fn is_identifier(name: &str) -> bool {
    const HARD_KEYWORDS: &[&str] = &[
        "as",
        "break",
        "class",
        "continue",
        "do",
        "else",
        "false",
        "for",
        "fun",
        "if",
        "in",
        "interface",
        "is",
        "null",
        "object",
        "package",
        "return",
        "super",
        "this",
        "throw",
        "true",
        "try",
        "typealias",
        "typeof",
        "val",
        "var",
        "when",
        "while",
    ];
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|first| first == '_' || first.is_ascii_alphabetic())
        && chars.all(|c| c == '_' || c.is_ascii_alphanumeric())
        && !HARD_KEYWORDS.contains(&name)
}

/// Builds one Kotlin file. Code fragments must be `'static`, so scene data
/// can only enter the output through the typed literal methods.
pub(crate) struct KotlinWriter {
    name: String,
    out: String,
    mapped: Vec<(SourceRange, Origin)>,
}

impl KotlinWriter {
    pub(crate) fn new(name: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            out: String::new(),
            mapped: Vec::new(),
        }
    }

    /// Fixed Kotlin code.
    pub(crate) fn code(&mut self, code: &'static str) -> &mut Self {
        self.out.push_str(code);
        self
    }

    /// A Kotlin identifier (class, object or package segment). Callers
    /// validate user-supplied names first; this is an invariant check.
    pub(crate) fn ident(&mut self, name: &str) -> &mut Self {
        assert!(is_identifier(name), "invalid Kotlin identifier {name:?}");
        self.out.push_str(name);
        self
    }

    /// A string literal.
    pub(crate) fn string(&mut self, value: &str) -> &mut Self {
        self.out.push_str(&kotlin_string(value));
        self
    }

    /// A `Long` literal; negative values are parenthesized.
    pub(crate) fn long(&mut self, value: i64) -> &mut Self {
        if value == i64::MIN {
            self.out.push_str("Long.MIN_VALUE");
        } else if value < 0 {
            self.out.push_str(&format!("({value}L)"));
        } else {
            self.out.push_str(&format!("{value}L"));
        }
        self
    }

    /// An `Int` literal from a non-negative index or count.
    pub(crate) fn int(&mut self, value: usize) -> &mut Self {
        let value = i32::try_from(value).expect("index fits a Kotlin Int");
        self.out.push_str(&value.to_string());
        self
    }

    /// A `Double` literal that parses back to exactly `value`. Rust's
    /// shortest round-trip rendering is also valid Kotlin syntax once a
    /// fraction or exponent is present.
    pub(crate) fn double(&mut self, value: f64) -> &mut Self {
        assert!(value.is_finite(), "non-finite literal reached the writer");
        let mut text = format!("{value:?}");
        if !text.contains(['.', 'e', 'E']) {
            text.push_str(".0");
        }
        if value.is_sign_negative() {
            self.out.push('(');
            self.out.push_str(&text);
            self.out.push(')');
        } else {
            self.out.push_str(&text);
        }
        self
    }

    /// An opaque ARGB color `Int` from `0xRRGGBB`.
    pub(crate) fn color(&mut self, rgb: u32) -> &mut Self {
        self.out
            .push_str(&format!("0xFF{:06X}.toInt()", rgb & 0x00ff_ffff));
        self
    }

    /// A Boolean literal.
    pub(crate) fn boolean(&mut self, value: bool) -> &mut Self {
        self.out.push_str(if value { "true" } else { "false" });
        self
    }

    /// Record everything `write` emits as generated from `origin`.
    pub(crate) fn mapped(&mut self, origin: Origin, write: impl FnOnce(&mut Self)) -> &mut Self {
        let start = self.out.len();
        write(self);
        let end = self.out.len();
        self.mapped.push((SourceRange { start, end }, origin));
        self
    }

    /// Finish the file and resolve its mapped origins in `handoff`.
    /// Every origin must resolve: the writer only maps admitted constructs.
    pub(crate) fn finish(self, handoff: &SemanticHandoffV2) -> (KotlinFile, Vec<SourceMapEntry>) {
        let entries = self
            .mapped
            .into_iter()
            .map(|(generated, origin)| {
                let source = handoff
                    .origin(&origin)
                    .unwrap_or_else(|| panic!("unresolvable origin {origin:?}"));
                SourceMapEntry {
                    file: self.name.clone(),
                    generated,
                    origin,
                    source,
                }
            })
            .collect();
        (
            KotlinFile {
                name: self.name,
                text: self.out,
            },
            entries,
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn literals_are_valid_and_round_trip_their_values() {
        let mut writer = KotlinWriter::new("T.kt");
        writer
            .long(i64::MIN)
            .code(" ")
            .long(-5)
            .code(" ")
            .double(1e-7)
            .code(" ")
            .double(3.0)
            .code(" ")
            .double(-0.0)
            .code(" ")
            .string("a\"$\\é😀\u{7}")
            .code(" ")
            .color(0x12ab_cdef);
        assert_eq!(
            writer.out,
            "Long.MIN_VALUE (-5L) 1e-7 3.0 (-0.0) \"a\\\"\\$\\\\\\u00e9\\ud83d\\ude00\\u0007\" 0xFFABCDEF.toInt()"
        );
    }
}
