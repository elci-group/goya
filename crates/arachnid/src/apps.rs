//! `@apps`: opening other applications on the TV. Contract
//! `arachnid.apps/0.0.1`.
//!
//! A scene names the applications it may open:
//!
//! ```text
//! @apps tv { id: "apps.tv"; app browser: "com.webos.app.browser"; }
//! ```
//!
//! and opens one with a D2 `network` request `tv launch browser`, whose
//! text result says what happened. Arachnid checks every request at
//! compile time (`GY-AR-652`), so the generated runtime can only launch an
//! application the scene declared. The scene contains no platform code.
//!
//! **Lowering.** The runtime calls the Luna service
//! `luna://com.webos.applicationManager/launch` with `{"id": APP_ID}`
//! through the page's `PalmServiceBridge`. Luna is webOS's system message
//! bus, so a launch is outbound I/O from the app's point of view, which is
//! why it is a `network` effect rather than a new effect kind (the
//! determinism contract is unchanged).
//!
//! **Not yet observed on a device.** Whether a third-party app may call
//! this method on the owner's TV is checked by `examples/luna_probe.rs`
//! (docs/arachnid/launcher.md §4). Without a bridge, or when the TV
//! refuses, the request returns a sentence saying so; it never throws.

use crate::appinfo::json_string;
use crate::diagnostics::{Code, Diagnostic};
use goya_lang::{EffectValueType, InteractionClass, ParsedScene};

pub const CONTRACT: &str = "arachnid.apps/0.0.1";
pub const SERVICE: &str = "luna://com.webos.applicationManager/launch";
pub const FILE: &str = "apps.js";
/// The runtime uses only ES5 and `Promise`; Chromium 53 (webOS 4.x) has both.
pub const MIN_CHROMIUM: u16 = 53;

/// An application id LG accepts: lowercase letters, digits, `.` and `-`.
fn app_id_ok(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 128
        && id.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'.' || b == b'-' || b == b'_')
}

/// Check the scene's `@apps` declarations and every request addressed to them.
pub fn check(parsed: &ParsedScene) -> Vec<Diagnostic> {
    let decls = &parsed.declarations.apps;
    let mut out = Vec::new();
    let refuse = |m: String| Diagnostic::new(Code::LaunchContract, m);
    if decls.len() > 1 {
        out.push(refuse("only one @apps per scene is lowered to webOS".into()));
    }
    for d in decls {
        if parsed.declarations.links.iter().any(|l| l.name == d.name) {
            out.push(refuse(format!("@apps {} has the same name as a @link", d.name)).at(Some(d.range)));
        }
        for (name, id) in &d.apps {
            if !app_id_ok(id) {
                out.push(refuse(format!("app {name} in @apps {} has id {id:?}, which is not a webOS application id", d.name)).at(Some(d.range)));
            }
        }
    }
    for i in parsed.scene.interactions.iter().filter(|i| i.class == InteractionClass::D2) {
        for r in &i.requests {
            let words: Vec<&str> = r.request_utf8.split(' ').collect();
            let Some(d) = decls.iter().find(|d| words.first() == Some(&d.name.as_str())) else {
                continue;
            };
            if r.effect_kind.as_str() != "network" || r.result_type != EffectValueType::Text {
                out.push(refuse(format!("requests to @apps {} are network effects with a text result ({})", d.name, i.name)));
            }
            let ok = matches!(words.as_slice(), [_, "launch", app] if d.apps.iter().any(|(n, _)| n == app));
            if !ok {
                out.push(refuse(format!(
                    "request \"{}\" in {} is not \"{} launch APP\" with an app declared in @apps {}",
                    r.request_utf8, i.name, d.name, d.name
                )));
            }
        }
    }
    out
}

fn config_js(parsed: &ParsedScene) -> Option<String> {
    let d = parsed.declarations.apps.first()?;
    let apps: Vec<String> = d
        .apps
        .iter()
        .map(|(n, id)| format!("{}:{}", json_string(n), json_string(id)))
        .collect();
    Some(
        format!("{{name:{},apps:{{{}}}}}", json_string(&d.name), apps.join(","))
            .replace('<', "\\u003c"),
    )
}

/// The runtime for the scene's `@apps`, or `None` when it declares none.
pub fn runtime_js(parsed: &ParsedScene) -> Option<String> {
    let config = config_js(parsed)?;
    Some(
        RUNTIME
            .replace("__CONTRACT__", CONTRACT)
            .replace("__SERVICE__", SERVICE)
            .replace("__CONFIG__", &config),
    )
}

const RUNTIME: &str = r#"/* Generated by Arachnid (__CONTRACT__): opens the applications the
   scene declares in @apps. Compiler output, identical for every app apart
   from CONFIG. */
(function () {
  "use strict";
  var CONFIG = __CONFIG__;
  var SERVICE = "__SERVICE__";
  var TIMEOUT_MS = 8000;
  var A = window.Arachnid;
  /* Bridges are kept until they answer, so they are not collected first. */
  var inflight = [];

  function call(uri, params) {
    return new Promise(function (resolve, reject) {
      var Bridge = window.PalmServiceBridge || window.WebOSServiceBridge;
      if (typeof Bridge !== "function") { reject(new Error("this TV offers no service bridge to the app")); return; }
      var bridge = new Bridge(), done = false;
      inflight.push(bridge);
      function finish() { done = true; inflight.splice(inflight.indexOf(bridge), 1); }
      var timer = setTimeout(function () { if (!done) { finish(); reject(new Error("the TV did not answer")); } }, TIMEOUT_MS);
      bridge.onservicecallback = function (msg) {
        if (done) return;
        clearTimeout(timer); finish();
        var r = null;
        try { r = JSON.parse(msg); } catch (e) { reject(new Error("the TV's answer was unreadable")); return; }
        if (r && r.returnValue === true) resolve(r);
        else reject(new Error((r && (r.errorText || r.errorCode)) || "the TV refused"));
      };
      bridge.call(uri, JSON.stringify(params));
    });
  }

  A.provide("network", function (request) {
    var w = request.split(" ");
    var id = w[1] === "launch" && CONFIG.apps.hasOwnProperty(w[2]) ? CONFIG.apps[w[2]] : null;
    if (id === null) return Promise.reject(new Error("@apps " + CONFIG.name + " has no request " + request));
    return call(SERVICE, { id: id }).then(
      function () { return "Opening " + w[2]; },
      function (e) { return "Could not open " + w[2] + ": " + e.message; });
  }, CONFIG.name);
})();
"#;

#[cfg(test)]
mod tests {
    use super::*;

    const SCENE: &str = r#"@ontology apps_fixture {
  @cell root { id: "root"; fill: #f4f1ea;
    @cell notice { id: "notice"; position_p: (0.05, 0.05, 0); extent_p: (0.9, 0.1, 0); text-from: state.notice; text-size-p: 0.5; }
    @button browser { id: "browser"; position_p: (0.05, 0.8, 0); extent_p: (0.3, 0.12, 0); text: "Browser"; text-size-p: 0.35; fill: #d9e2ec; remote-colour: red; }
  }
  @state { notice: text = "" session; }
  @apps tv { id: "apps.tv"; app browser: "com.webos.app.browser"; app pairs: "com.goya.arachnid.pairs"; }
  @interaction open_browser { id: "action.browser"; trigger: button.browser.activate; class: D2; effects { network; } requests { r: effect network capability "network" request "tv launch browser" result text; } state { write notice: text; } input { } set notice = effect.r; }
}
"#;

    fn diags(src: &str) -> Vec<String> {
        let parsed = goya_lang::parse_strict_gssh3_live(src).unwrap_or_else(|e| panic!("{e}"));
        let mut d = check(&parsed);
        d.extend(crate::lanlink::check(&parsed));
        d.iter().map(|d| d.message.clone()).collect()
    }

    #[test]
    fn fixture_is_lowered() {
        assert!(diags(SCENE).is_empty(), "{:?}", diags(SCENE));
        let js = runtime_js(&goya_lang::parse_strict_gssh3_live(SCENE).unwrap()).unwrap();
        assert!(js.contains(r#"var CONFIG = {name:"tv",apps:{"browser":"com.webos.app.browser","pairs":"com.goya.arachnid.pairs"}};"#), "{js}");
        assert!(js.contains(SERVICE));
    }

    #[test]
    fn launches_name_declared_apps() {
        assert!(diags(&SCENE.replace("tv launch browser", "tv launch netflix"))[0].contains("not \"tv launch APP\""));
        assert!(diags(&SCENE.replace("tv launch browser", "tv open browser"))[0].contains("not \"tv launch APP\""));
        assert!(diags(&SCENE.replace("tv launch browser", "tv launch browser now"))[0].contains("not \"tv launch APP\""));
        assert!(diags(&SCENE.replace("tv launch browser", "telly launch browser"))[0].contains("addressed to no @link or @apps"));
        assert!(diags(&SCENE.replace("com.webos.app.browser", "Com Browser"))[0].contains("not a webOS application id"));
    }

    #[test]
    fn no_apps_no_runtime() {
        let parsed = goya_lang::parse_strict_gssh3_live(include_str!("../fixtures/lanlink.gscene")).unwrap();
        assert!(runtime_js(&parsed).is_none());
        assert!(check(&parsed).is_empty());
    }
}
