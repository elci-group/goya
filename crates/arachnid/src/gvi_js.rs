//! The generated GY-GVI/0 runtime for webOS (`gvi.js`), generic across
//! apps. It is emitted by Rust, like `app.js`; no app ships its own script.
//!
//! The reference decoder (`goya_gvi::Inventory::open`) has already verified
//! every inventory at build time, and `app.js` passes the file's SHA-256,
//! which this runtime checks before decoding. So the decoder here reads the
//! structures it needs and stops at the first inconsistency, without
//! repeating the canonical-form and certificate checks:
//!
//! * GY-GFXC/1 header and directory (sections by tag);
//! * `INDX` keys and projection ids (identity, bitmap or packed keys);
//! * `PROJ` packed columns (frame of reference, dictionary, GVI-O mode 2);
//! * `GEOM` paths, and `DIFF` records (Copy, Extrapolate, Affine, GVI-A
//!   Lerp and BakedLerp, record or GVI-O columnar form) rebuilt in id order
//!   with the reference integer arithmetic (BigInt where products exceed
//!   2^53, rounding half to even);
//! * `STYL` or GVI-L `LSTY` styles.
//!
//! `crates/arachnid/tests/runtime/gvi-conformance.js` checks this decoder
//! against the reference decoder, state by state, under Node.

