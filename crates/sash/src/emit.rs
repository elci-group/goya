fn run() -> i32 {
    if TITLE_UTF8.len() != TITLE_LEN || TEXT_UTF8.len() != TEXT_LEN || SEMANTIC_ID_UTF8.len() != SEMANTIC_LEN {
        return fail("generated lengths do not match");
    }
    let title = match wide_utf8(TITLE_UTF8) {
        Some(value) => value,
        None => return fail("window title is not valid UTF-8"),
    };
    let text = match wide_utf8(TEXT_UTF8) {
        Some(value) => value,
        None => return fail("window text is not valid UTF-8"),
    };
    let identity = match wide_utf8(SEMANTIC_ID_UTF8) {
        Some(value) => value,
        None => return fail("semantic id is not valid UTF-8"),
    };
    LABEL.store(text.as_ptr() as *mut u16, Ordering::Relaxed);
    IDENTITY.store(identity.as_ptr() as *mut u16, Ordering::Relaxed);
    unsafe { create_and_run(title.as_ptr()) }
}

fn wide_utf8(bytes: &[u8]) -> Option<Vec<u16>> {
    let text = std::str::from_utf8(bytes).ok()?;
    if text.chars().any(|unit| unit == '\0') {
        return None;
    }
    let mut encoded: Vec<u16> = text.encode_utf16().collect();
    encoded.push(0);
    Some(encoded)
}

fn wide_ascii(text: &str) -> Vec<u16> {
    let mut encoded: Vec<u16> = text.encode_utf16().collect();
    encoded.push(0);
    encoded
}

fn fail(text: &str) -> i32 {
    let body = wide_ascii(text);
    let caption = wide_ascii("Sash");
    unsafe {
        MessageBoxW(std::ptr::null_mut(), body.as_ptr(), caption.as_ptr(), 0x10);
    }
    1
}

unsafe fn create_and_run(title: *const u16) -> i32 {
    let per_monitor_v2 = (-4isize) as usize as *mut c_void;
    if SetProcessDpiAwarenessContext(per_monitor_v2) == 0
        && AreDpiAwarenessContextsEqual(GetThreadDpiAwarenessContext(), per_monitor_v2) == 0
    {
        return fail("per-monitor DPI awareness is not active");
    }
    let class_name = wide_ascii("SashStaticWindow");
    let instance = GetModuleHandleW(std::ptr::null());
    if instance.is_null() {
        return fail("the process module handle is missing");
    }
    let cursor = LoadCursorW(std::ptr::null_mut(), 32512usize as *const u16);
    let class = WndClassExW {
        cb_size: std::mem::size_of::<WndClassExW>() as u32,
        style: 0x0001 | 0x0002,
        lpfn_wnd_proc: Some(wnd_proc),
        cb_cls_extra: 0,
        cb_wnd_extra: 0,
        h_instance: instance,
        h_icon: std::ptr::null_mut(),
        h_cursor: cursor,
        hbr_background: (5usize + 1) as *mut c_void,
        lpsz_menu_name: std::ptr::null(),
        lpsz_class_name: class_name.as_ptr(),
        h_icon_sm: std::ptr::null_mut(),
    };
    if RegisterClassExW(&class) == 0 {
        return fail("the window class was not registered");
    }
    let mut dpi = GetDpiForSystem();
    if dpi == 0 || dpi > 960 {
        dpi = 96;
    }
    let mut rect = Rect {
        left: 0,
        top: 0,
        right: scale(CLIENT_DIP_W, dpi),
        bottom: scale(CLIENT_DIP_H, dpi),
    };
    if AdjustWindowRectExForDpi(&mut rect, WS_OVERLAPPEDWINDOW, 0, 0, dpi) == 0 {
        return fail("the window frame size was not calculated");
    }
    let width = rect.right.saturating_sub(rect.left);
    let height = rect.bottom.saturating_sub(rect.top);
    if width <= 0 || height <= 0 {
        return fail("the window frame size is empty");
    }
    let hwnd = CreateWindowExW(
        0,
        class_name.as_ptr(),
        title,
        WS_OVERLAPPEDWINDOW | WS_CLIPCHILDREN,
        CW_USEDEFAULT,
        CW_USEDEFAULT,
        width,
        height,
        std::ptr::null_mut(),
        std::ptr::null_mut(),
        instance,
        std::ptr::null_mut(),
    );
    if hwnd.is_null() {
        return fail("the window was not created");
    }
    ShowWindow(hwnd, SW_SHOWNORMAL);
    UpdateWindow(hwnd);
    let mut message = std::mem::zeroed::<Msg>();
    loop {
        let status = GetMessageW(&mut message, std::ptr::null_mut(), 0, 0);
        if status == 0 {
            break;
        }
        if status < 0 {
            return 1;
        }
        TranslateMessage(&message);
        DispatchMessageW(&message);
    }
    LABEL.store(std::ptr::null_mut(), Ordering::Relaxed);
    IDENTITY.store(std::ptr::null_mut(), Ordering::Relaxed);
    CHILD.store(std::ptr::null_mut(), Ordering::Relaxed);
    message.wparam as i32
}

fn scale(dip: i32, dpi: u32) -> i32 {
    ((dip as u32).saturating_mul(dpi) / 96) as i32
}

unsafe extern "system" fn wnd_proc(hwnd: *mut c_void, message: u32, wparam: usize, lparam: isize) -> isize {
    match message {
        WM_CREATE => {
            if setup(hwnd) != 0 {
                return -1;
            }
            0
        }
        WM_SIZE => {
            place_child(hwnd);
            0
        }
        WM_DPICHANGED => {
            let rect = lparam as *const Rect;
            if !rect.is_null() {
                let rect = &*rect;
                let width = rect.right.saturating_sub(rect.left);
                let height = rect.bottom.saturating_sub(rect.top);
                SetWindowPos(hwnd, std::ptr::null_mut(), rect.left, rect.top, width, height, SWP_NOZORDER | SWP_NOACTIVATE);
            }
            0
        }
        WM_DESTROY => {
            let child = CHILD.load(Ordering::Relaxed);
            RemovePropW(hwnd, PROP_SEMANTIC.as_ptr());
            if !child.is_null() {
                RemovePropW(child, PROP_SEMANTIC.as_ptr());
            }
            PostQuitMessage(0);
            0
        }
        _ => DefWindowProcW(hwnd, message, wparam, lparam),
    }
}

unsafe fn setup(hwnd: *mut c_void) -> i32 {
    let label = LABEL.load(Ordering::Relaxed);
    let identity = IDENTITY.load(Ordering::Relaxed);
    if label.is_null() || identity.is_null() {
        return 1;
    }
    let static_class = wide_ascii("STATIC");
    let instance = GetModuleHandleW(std::ptr::null());
    let child = CreateWindowExW(
        0,
        static_class.as_ptr(),
        label,
        WS_CHILD | WS_VISIBLE | SS_NOPREFIX,
        0,
        0,
        scale(CLIENT_DIP_W, 96),
        scale(CLIENT_DIP_H, 96),
        hwnd,
        std::ptr::null_mut(),
        instance,
        std::ptr::null_mut(),
    );
    if child.is_null() {
        return 1;
    }
    let font = GetStockObject(DEFAULT_GUI_FONT);
    if font.is_null() {
        return 1;
    }
    SendMessageW(child, WM_SETFONT, font as usize, 1);
    if SetPropW(hwnd, PROP_SEMANTIC.as_ptr(), identity as *mut c_void) == 0
        || SetPropW(child, PROP_SEMANTIC.as_ptr(), identity as *mut c_void) == 0
    {
        return 1;
    }
    CHILD.store(child, Ordering::Relaxed);
    place_child(hwnd);
    0
}

unsafe fn place_child(parent: *mut c_void) {
    let child = CHILD.load(Ordering::Relaxed);
    if child.is_null() {
        return;
    }
    let mut dpi = GetDpiForWindow(parent);
    if dpi == 0 || dpi > 960 {
        dpi = 96;
    }
    let want_w = scale(CLIENT_DIP_W, dpi);
    let want_h = scale(CLIENT_DIP_H, dpi);
    let mut rect = Rect { left: 0, top: 0, right: 0, bottom: 0 };
    if GetClientRect(parent, &mut rect) == 0 {
        return;
    }
    let client_w = rect.right.saturating_sub(rect.left).max(0);
    let client_h = rect.bottom.saturating_sub(rect.top).max(0);
    MoveWindow(child, 0, 0, want_w.min(client_w), want_h.min(client_h), 1);
}
