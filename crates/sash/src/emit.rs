//! Structured emission of one native Rust window.
//!
//! Authored text is emitted as decimal bytes. It is never interpolated into
//! a Rust string, a resource script, or a command line.

use crate::admit::AdmittedWindow;
use crate::{hex_encode, sha256_hex};

pub struct Generated {
    pub main_rs: String,
    pub cargo_toml: &'static str,
    pub build_rs: &'static str,
    pub manifest_xml: String,
    pub resource_script: String,
    pub source_map: serde_json::Value,
}

pub fn generate(window: &AdmittedWindow) -> Generated {
    let mut main = String::new();
    main.push_str("// Generated by Sash ");
    main.push_str(crate::admit::PROFILE);
    main.push_str("\n// source-digest: ");
    main.push_str(&hex_encode(&window.source_digest));
    main.push_str("\n// The user-facing deliverable is the linked App.exe.\n");
    main.push_str("#![windows_subsystem = \"windows\"]\n\n");
    let title = array_line(&mut main, "TITLE_UTF8", window.scene_name.as_bytes());
    let identity = array_line(&mut main, "ROOT_ID_UTF8", window.semantic_id.as_bytes());
    main.push_str(&format!(
        "const TITLE_LEN: usize = {};\n",
        window.scene_name.len()
    ));
    main.push_str(&format!(
        "const ROOT_ID_LEN: usize = {};\n",
        window.semantic_id.len()
    ));
    let mut label_ranges = Vec::new();
    for (index, label) in window.labels.iter().enumerate() {
        let text_name = format!("TEXT_{index}");
        let id_name = format!("ID_{index}");
        let text_range = array_line(&mut main, &text_name, label.text.as_bytes());
        let id_range = array_line(&mut main, &id_name, label.semantic_id.as_bytes());
        main.push_str(&format!(
            "const TEXT_{index}_LEN: usize = {};\n",
            label.text.len()
        ));
        main.push_str(&format!(
            "const ID_{index}_LEN: usize = {};\n",
            label.semantic_id.len()
        ));
        label_ranges.push((label, text_range, id_range));
    }
    main.push_str(
        "struct Placed { text: &'static [u8], text_len: usize, id: &'static [u8], id_len: usize, x: i32, y: i32, w: i32, h: i32 }\n",
    );
    main.push_str("const PLACED: &[Placed] = &[\n");
    let mut placed_ranges = Vec::new();
    for (index, label) in window.labels.iter().enumerate() {
        let start = main.len();
        main.push_str(&format!(
            "    Placed {{ text: TEXT_{index}, text_len: TEXT_{index}_LEN, id: ID_{index}, id_len: ID_{index}_LEN, x: {}, y: {}, w: {}, h: {} }},\n",
            label.x_dip, label.y_dip, label.width_dip, label.height_dip
        ));
        placed_ranges.push((start, main.len()));
    }
    main.push_str("];\n");
    let width_at = main.len();
    main.push_str(&format!(
        "const CLIENT_DIP_W: i32 = {};\n",
        window.width_dip
    ));
    let width_end = main.len();
    let height_at = main.len();
    main.push_str(&format!(
        "const CLIENT_DIP_H: i32 = {};\n",
        window.height_dip
    ));
    let height_end = main.len();
    main.push_str(PROGRAM);
    let digest = sha256_hex(main.as_bytes());
    let mut origins = vec![
        origin("title", &title, &window.ontology_range, &window.semantic_id),
        origin("id", &identity, &window.id_range, &window.semantic_id),
        origin(
            "extent-width",
            &(width_at, width_end),
            &window.extent_range,
            &window.semantic_id,
        ),
        origin(
            "extent-height",
            &(height_at, height_end),
            &window.extent_range,
            &window.semantic_id,
        ),
    ];
    for (label, text_range, id_range) in &label_ranges {
        origins.push(origin(
            "text",
            text_range,
            &label.text_range,
            &label.semantic_id,
        ));
        origins.push(origin("id", id_range, &label.id_range, &label.semantic_id));
    }
    for (label, placed) in window.labels.iter().zip(&placed_ranges) {
        origins.push(origin(
            "extent",
            placed,
            &label.extent_range,
            &label.semantic_id,
        ));
    }
    let source_map = serde_json::json!({
        "schema_version": "1",
        "generator": "sash",
        "profile": crate::admit::PROFILE,
        "source_digest": hex_encode(&window.source_digest),
        "generated_digest": digest,
        "files": [{
            "path": "evidence/generated-main.rs",
            "origins": origins,
        }]
    });
    Generated {
        main_rs: main,
        cargo_toml: CARGO_TOML,
        build_rs: BUILD_RS,
        manifest_xml: MANIFEST.to_string(),
        resource_script: RESOURCE_SCRIPT.to_string(),
        source_map,
    }
}

pub(crate) fn array_line(out: &mut String, name: &str, bytes: &[u8]) -> (usize, usize) {
    out.push_str("const ");
    out.push_str(name);
    out.push_str(": &[u8] = &");
    let start = out.len();
    out.push('[');
    for (index, byte) in bytes.iter().enumerate() {
        if index > 0 {
            out.push(',');
        }
        out.push_str(&byte.to_string());
    }
    out.push(']');
    let end = out.len();
    out.push_str(";\n");
    (start, end)
}

pub(crate) fn origin(
    property: &str,
    generated: &(usize, usize),
    source: &goya_lang::SourceRange,
    semantic_id: &str,
) -> serde_json::Value {
    serde_json::json!({
        "property": property,
        "semantic_id": semantic_id,
        "generated_range": {"start": generated.0, "end": generated.1},
        "source_range": {"start": source.start, "end": source.end},
    })
}

