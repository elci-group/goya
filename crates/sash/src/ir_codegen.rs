fn wide_utf8(bytes: &[u8]) -> Option<Vec<u16>> {
    let text = std::str::from_utf8(bytes).ok()?;
    if text.chars().any(|unit| unit == '\0') {
        return None;
    }
    let mut encoded: Vec<u16> = text.encode_utf16().collect();
    encoded.push(0);
    Some(encoded)
}

fn wide_ascii(text: &str) -> Vec<u16> {
    let mut encoded: Vec<u16> = text.encode_utf16().collect();
    encoded.push(0);
    encoded
}

