//! Code generation from IR to the sash `Generated` output.

use crate::emit::{array_line, origin};
use crate::sha256_hex;
use sash_ir::*;

/// The IR carries its own `SourceRange` so sash-ir stays independent of
/// goya-lang. Both are half-open UTF-8 byte offsets with identical layout;
/// convert at the emit boundary where the origin helper wants the language
/// type. Field-for-field parity is pinned by `source_range_layout_parity`.
fn to_lang_range(range: &SourceRange) -> goya_lang::SourceRange {
    goya_lang::SourceRange {
        start: range.start,
        end: range.end,
    }
}

/// Generate code from IR for one API floor.
///
/// The floor selects the Win32 adapter only: admission decided what the
/// window means, the IR carries it, and the floor decides which Win32
/// implementation the emitted program uses. The win10 floor is the adapter
/// of the first proof; the win8 floor is the system-DPI-aware variant.
pub fn codegen_from_ir(ir: &IrDocument, floor: crate::api_floor::ApiFloor) -> crate::emit::Generated {
    match ir.profile.as_str() {
        p if p.starts_with("sash.win32.static-window") => match floor {
            crate::api_floor::ApiFloor::Win10 => codegen_static_window(ir, PROGRAM_STATIC),
            crate::api_floor::ApiFloor::Win8 => {
                codegen_static_window(ir, PROGRAM_STATIC_LEGACY)
            }
        },
        p if p.starts_with("sash.win32.interactive") => match floor {
            crate::api_floor::ApiFloor::Win10 => codegen_interactive_window(ir, PROGRAM_INTERACTIVE),
            crate::api_floor::ApiFloor::Win8 => {
                codegen_interactive_window(ir, PROGRAM_INTERACTIVE_LEGACY)
            }
        },
        _ => panic!("Unknown profile: {}", ir.profile),
    }
}

fn codegen_static_window(
    ir: &IrDocument,
    program: &str,
) -> crate::emit::Generated {
    let mut main = String::new();
    main.push_str("// Generated by Sash ");
    main.push_str(&ir.profile);
    main.push_str("\n// source-digest: ");
    main.push_str(&ir.provenance.source_digest);
    main.push_str("\n// The user-facing deliverable is the linked App.exe.\n");
    main.push_str("#![windows_subsystem = \"windows\"]\n\n");

    let title = array_line(&mut main, "TITLE_UTF8", &ir.identity.title_utf8);
    let identity = array_line(&mut main, "ROOT_ID_UTF8", &ir.identity.root_id_utf8);
    main.push_str(&format!(
        "const TITLE_LEN: usize = {};\n",
        ir.identity.title_len
    ));
    main.push_str(&format!(
        "const ROOT_ID_LEN: usize = {};\n",
        ir.identity.root_id_len
    ));

    let mut label_ranges = Vec::new();
    for control in &ir.controls {
        let text_name = format!("TEXT_{}", control.index);
        let id_name = format!("ID_{}", control.index);
        let text_range = array_line(&mut main, &text_name, control.text.as_bytes());
        let id_range = array_line(&mut main, &id_name, control.semantic_id.as_bytes());
        main.push_str(&format!(
            "const TEXT_{}_LEN: usize = {};\n",
            control.index,
            control.text.len()
        ));
        main.push_str(&format!(
            "const ID_{}_LEN: usize = {};\n",
            control.index,
            control.semantic_id.len()
        ));
        label_ranges.push((control, text_range, id_range));
    }

    main.push_str(
        "struct Placed { text: &'static [u8], text_len: usize, id: &'static [u8], id_len: usize, x: i32, y: i32, w: i32, h: i32 }\n",
    );
    main.push_str("const PLACED: &[Placed] = &[\n");
    let mut placed_ranges = Vec::new();
    for control in &ir.controls {
        let start = main.len();
        main.push_str(&format!(
            "    Placed {{ text: TEXT_{}, text_len: TEXT_{}_LEN, id: ID_{}, id_len: ID_{}_LEN, x: {}, y: {}, w: {}, h: {} }},\n",
            control.index, control.index, control.index, control.index,
            control.x_dip, control.y_dip, control.width_dip, control.height_dip
        ));
        placed_ranges.push((start, main.len()));
    }
    main.push_str("];\n");
    let width_at = main.len();
    main.push_str(&format!(
        "const CLIENT_DIP_W: i32 = {};\n",
        ir.window.width_dip
    ));
    let width_end = main.len();
    let height_at = main.len();
    main.push_str(&format!(
        "const CLIENT_DIP_H: i32 = {};\n",
        ir.window.height_dip
    ));
    let height_end = main.len();
    main.push_str(program);
    let digest = sha256_hex(main.as_bytes());

    let mut origins = vec![
        origin("title", &title, &to_lang_range(&ir.provenance.ontology_range), &ir.window.semantic_id),
        origin("id", &identity, &to_lang_range(&ir.provenance.id_range), &ir.window.semantic_id),
        origin(
            "extent-width",
            &(width_at, width_end),
            &to_lang_range(&ir.provenance.extent_range),
            &ir.window.semantic_id,
        ),
        origin(
            "extent-height",
            &(height_at, height_end),
            &to_lang_range(&ir.provenance.extent_range),
            &ir.window.semantic_id,
        ),
    ];

    for (control, text_range, id_range) in &label_ranges {
        let origin_info = ir.provenance.control_origins.iter().find(|o| o.index == control.index).unwrap();
        origins.push(origin(
            "text",
            text_range,
            &to_lang_range(&origin_info.text_range),
            &control.semantic_id,
        ));
        origins.push(origin("id", id_range, &to_lang_range(&origin_info.id_range), &control.semantic_id));
    }

    for (control, placed) in ir.controls.iter().zip(&placed_ranges) {
        let origin_info = ir.provenance.control_origins.iter().find(|o| o.index == control.index).unwrap();
        origins.push(origin(
            "extent",
            placed,
            &to_lang_range(&origin_info.extent_range),
            &control.semantic_id,
        ));
    }

    let source_map = serde_json::json!({
        "schema_version": "1",
        "generator": "sash",
        "profile": ir.profile,
        "source_digest": ir.provenance.source_digest,
        "generated_digest": digest,
        "files": [{
            "path": "evidence/generated-main.rs",
            "origins": origins,
        }]
    });

    // Cargo.toml and build.rs are fixed compiler text for every profile, so
    // they stay &'static in the output. The IR still carries them; the
    // assertions keep that copy honest.
    debug_assert_eq!(ir.resources.cargo_toml, crate::emit::CARGO_TOML);
    debug_assert_eq!(ir.resources.build_rs, crate::emit::BUILD_RS);
    crate::emit::Generated {
        main_rs: main,
        cargo_toml: crate::emit::CARGO_TOML,
        build_rs: crate::emit::BUILD_RS,
        manifest_xml: ir.resources.manifest_xml.clone(),
        resource_script: ir.resources.resource_script.clone(),
        source_map,
    }
}

fn codegen_interactive_window(
    ir: &IrDocument,
    program: &str,
) -> crate::emit::Generated {
    let mut main = String::new();
    main.push_str("// Generated by Sash ");
    main.push_str(&ir.profile);
    main.push_str("\n// source-digest: ");
    main.push_str(&ir.provenance.source_digest);
    main.push_str("\n// runtime_qualification: BLOCKED\n");
    main.push_str("#![windows_subsystem = \"windows\"]\n\n");
    main.push_str("use std::sync::atomic::{AtomicI64, AtomicU64};\n");

    let title = array_line(&mut main, "TITLE_UTF8", &ir.identity.title_utf8);
    let identity = array_line(&mut main, "ROOT_ID_UTF8", &ir.identity.root_id_utf8);
    main.push_str(&format!(
        "const TITLE_LEN: usize = {};\n",
        ir.identity.title_len
    ));
    main.push_str(&format!(
        "const ROOT_ID_LEN: usize = {};\n",
        ir.identity.root_id_len
    ));

    main.push_str(
        "const ROLE_STATIC: u8 = 1;\nconst ROLE_EDIT: u8 = 2;\nconst ROLE_BUTTON: u8 = 3;\n",
    );
    main.push_str("struct Placed { role: u8, control_id: u16, text: &'static [u8], text_len: usize, id: &'static [u8], id_len: usize, x: i32, y: i32, w: i32, h: i32 }\n");

    let mut text_ranges = Vec::new();
    for control in &ir.controls {
        let text_name = format!("TEXT_{}", control.index);
        let id_name = format!("ID_{}", control.index);
        let text_range = array_line(&mut main, &text_name, control.text.as_bytes());
        let id_range = array_line(&mut main, &id_name, control.semantic_id.as_bytes());
        main.push_str(&format!(
            "const TEXT_{}_LEN: usize = {};\nconst ID_{}_LEN: usize = {};\n",
            control.index,
            control.text.len(),
            control.index,
            control.semantic_id.len()
        ));
        text_ranges.push((text_range, id_range));
    }

    main.push_str("const PLACED: &[Placed] = &[\n");
    let mut placed_ranges = Vec::new();
    for control in &ir.controls {
        let start = main.len();
        let role_value = match control.role {
            ControlRole::Static => 1,
            ControlRole::Edit => 2,
            ControlRole::Button => 3,
        };
        main.push_str(&format!(
            "    Placed {{ role: {}, control_id: {}, text: TEXT_{}, text_len: TEXT_{}_LEN, id: ID_{}, id_len: ID_{}_LEN, x: {}, y: {}, w: {}, h: {} }},\n",
            role_value, control.control_id, control.index, control.index, control.index, control.index,
            control.x_dip, control.y_dip, control.width_dip, control.height_dip
        ));
        placed_ranges.push((start, main.len()));
    }
    main.push_str("];\n");

    let width_at = main.len();
    main.push_str(&format!("const CLIENT_DIP_W: i32 = {};\n", ir.window.width_dip));
    let width_end = main.len();
    let height_at = main.len();
    main.push_str(&format!("const CLIENT_DIP_H: i32 = {};\n", ir.window.height_dip));
    let height_end = main.len();

    let transition = ir.transition.as_ref().unwrap();
    let gesture = ir.gesture_policy.as_ref().unwrap();

    main.push_str(&format!(
        "const STATE_INDEX: usize = {};\nconst INPUT_INDEX: usize = {};\nconst BUTTON_INDEX: usize = {};\nconst BUTTON_ID: u16 = {};\n",
        transition.state_index,
        transition.input_index,
        transition.button_index,
        transition.button_id
    ));

    main.push_str(&format!(
        "const INITIAL_STATE: i64 = {};\nconst INITIAL_INPUT: i64 = {};\nconst COPY_ALLOWED: bool = {};\nconst PASTE_ALLOWED: bool = {};\nconst CUT_MODE: u8 = {};\n",
        literal(transition.initial_state),
        literal(transition.initial_input),
        gesture.copy_allowed,
        gesture.paste_allowed,
        gesture.cut_mode as u8
    ));

    main.push_str("static COUNT: AtomicI64 = AtomicI64::new(INITIAL_STATE);\n");
    main.push_str("static REVISION: AtomicU64 = AtomicU64::new(0);\n");
    main.push_str(include_str!("interactive_text.rs"));
    main.push('\n');
    main.push_str(include_str!("interactive_clipboard.rs"));
    main.push('\n');
    main.push_str(include_str!("interactive_keys.rs"));
    main.push('\n');
    main.push_str(include_str!("interactive_commit.rs"));
    main.push('\n');

    let transition_at = main.len();
    main.push_str(&emit_transition_from_ir(&transition.expr));
    let transition_end = main.len();

    main.push_str(
        "fn commit_transition(state_value: i64, revision: u64, input_value: i64) -> Option<(i64, u64)> {\n    let next = transition(state_value, input_value)?;\n    Some((next, revision.checked_add(1)?))\n}\n",
    );
    main.push_str(program);

    let digest = sha256_hex(main.as_bytes());

    let mut origins = vec![
        origin("title", &title, &to_lang_range(&ir.provenance.ontology_range), &ir.window.semantic_id),
        origin("id", &identity, &to_lang_range(&ir.provenance.id_range), &ir.window.semantic_id),
        origin(
            "extent-width",
            &(width_at, width_end),
            &to_lang_range(&ir.provenance.extent_range),
            &ir.window.semantic_id,
        ),
        origin(
            "extent-height",
            &(height_at, height_end),
            &to_lang_range(&ir.provenance.extent_range),
            &ir.window.semantic_id,
        ),
        origin(
            "interaction",
            &(transition_at, transition_end),
            &to_lang_range(&transition.action_range),
            &transition.action_id,
        ),
    ];

    for (control, (text_range, id_range)) in ir.controls.iter().zip(&text_ranges) {
        let origin_info = ir.provenance.control_origins.iter().find(|o| o.index == control.index).unwrap();
        origins.push(origin(
            "text",
            text_range,
            &to_lang_range(&origin_info.text_range),
            &control.semantic_id,
        ));
        origins.push(origin(
            "id",
            id_range,
            &to_lang_range(&origin_info.id_range),
            &control.semantic_id,
        ));
    }

    for (control, placed) in ir.controls.iter().zip(&placed_ranges) {
        let origin_info = ir.provenance.control_origins.iter().find(|o| o.index == control.index).unwrap();
        origins.push(origin(
            "extent",
            placed,
            &to_lang_range(&origin_info.extent_range),
            &control.semantic_id,
        ));
    }

    // Cargo.toml and build.rs are fixed compiler text for every profile, so
    // they stay &'static in the output. The IR still carries them; the
    // assertions keep that copy honest.
    debug_assert_eq!(ir.resources.cargo_toml, crate::emit::CARGO_TOML);
    debug_assert_eq!(ir.resources.build_rs, crate::emit::BUILD_RS);
    crate::emit::Generated {
        main_rs: main,
        cargo_toml: crate::emit::CARGO_TOML,
        build_rs: crate::emit::BUILD_RS,
        manifest_xml: ir.resources.manifest_xml.clone(),
        resource_script: ir.resources.resource_script.clone(),
        source_map: serde_json::json!({
            "schema_version": "1",
            "generator": "sash",
            "profile": ir.profile,
            "source_digest": ir.provenance.source_digest,
            "generated_digest": digest,
            "files": [{
                "path": "evidence/generated-main.rs",
                "origins": origins,
            }]
        }),
    }
}

fn literal(value: i64) -> String {
    if value == i64::MIN {
        "i64::MIN".into()
    } else {
        format!("{value}")
    }
}

pub(crate) fn emit_transition_from_ir(expr: &IntExpr) -> String {
    format!(
        "fn transition(state_value: i64, input_value: i64) -> Option<i64> {{\n    {}\n}}\n",
        emit_expr_from_ir(expr)
    )
}

fn emit_expr_from_ir(expr: &IntExpr) -> String {
    match expr {
        IntExpr::State => "Some(state_value)".into(),
        IntExpr::Input => "Some(input_value)".into(),
        IntExpr::Literal(value) => {
            if *value == i64::MIN {
                "Some(i64::MIN)".into()
            } else {
                format!("Some({value}_i64)")
            }
        }
        IntExpr::Add(left, right) => format!(
            "({}).and_then(|left| ({}).and_then(|right| left.checked_add(right)))",
            emit_expr_from_ir(left),
            emit_expr_from_ir(right)
        ),
    }
}


