//! Experimental Swift source for one verified D1 transition. No Apple toolchain
//! verification or iOS admission is implied by this module.
use crate::{
    swift,
    transition::{self, Expression, Operation},
};
use goya_lang::{InteractionType, InteractionValue, SourceRange};
use std::collections::BTreeMap;
use std::fmt::Write;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Field {
    pub source_key: String,
    pub swift_name: String,
    pub value_type: InteractionType,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Preview {
    pub swift: String,
    pub action: transition::SemanticId,
    pub trigger: transition::SemanticId,
    pub source_range: SourceRange,
    pub source_digest: [u8; 32],
    pub reference_program_hash: [u8; 32],
    pub state_fields: Vec<Field>,
    pub input_fields: Vec<Field>,
}

impl Preview {
    /// Versioned machine-readable source preview and explicit limitations.
    pub fn to_json(&self) -> serde_json::Value {
        fn fields(items: &[Field]) -> Vec<serde_json::Value> {
            items.iter().map(|field| serde_json::json!({"source_key":field.source_key,"swift_name":field.swift_name,"type":swift_type(field.value_type)})).collect()
        }
        fn hex(bytes: &[u8]) -> String {
            bytes.iter().map(|byte| format!("{byte:02x}")).collect()
        }
        serde_json::json!({"schema_version":"1", "operation":"preview-transition", "verification":"SOURCE_PREVIEW", "swift":self.swift,
            "action":{"module":self.action.module,"declared_id":self.action.declared_id},
            "trigger":{"module":self.trigger.module,"declared_id":self.trigger.declared_id},
            "source_range":{"start_byte":self.source_range.start,"end_byte":self.source_range.end},
            "source_sha256":hex(&self.source_digest), "reference_program_hash":hex(&self.reference_program_hash),
            "d1_vm_version":goya_executable::D1_VM_VERSION,
            "state_fields":fields(&self.state_fields), "input_fields":fields(&self.input_fields),
            "stages":{"apple_validation":"NOT_RUN", "runtime_limit_parity":"NOT_VERIFIED", "ios_admission":"NOT_RUN"}})
    }
}

// All code-bearing names are generated by Neptune. Source key strings are
// kept in metadata and are never interpolated into Swift syntax.
#[derive(Debug)]
enum SwiftExpr {
    Int(i64),
    Text(String),
    Bool(bool),
    State(usize, InteractionType),
    Input(usize, InteractionType),
    CheckedAdd(Box<SwiftExpr>, Box<SwiftExpr>),
}

impl SwiftExpr {
    fn emit_register(&self, out: &mut String, next: &mut usize) -> usize {
        let (ty, expression) = match self {
            Self::Int(i64::MIN) => (InteractionType::Int, "Int64.min".to_owned()),
            Self::Int(v) => (InteractionType::Int, v.to_string()),
            Self::Text(v) => (
                InteractionType::Text,
                swift::Expr::StringLiteral(v.clone()).render(),
            ),
            Self::Bool(v) => (InteractionType::Bool, v.to_string()),
            Self::State(index, ty) => (*ty, format!("state.s{index}")),
            Self::Input(index, ty) => (*ty, format!("input.i{index}")),
            Self::CheckedAdd(left, right) => {
                let left = left.emit_register(out, next);
                let right = right.emit_register(out, next);
                (
                    InteractionType::Int,
                    format!("try checkedAdd(r{left}, r{right})"),
                )
            }
        };
        let index = *next;
        *next += 1;
        let _ = writeln!(
            out,
            "        let r{index}: {} = {expression}",
            swift_type(ty)
        );
        let name_bytes = format!("r{index}").len();
        match ty {
            InteractionType::Text => {
                let _ = writeln!(
                    out,
                    "        registerBytes += {name_bytes} + r{index}.utf8.count"
                );
            }
            InteractionType::Int => {
                let _ = writeln!(
                    out,
                    "        registerBytes += {}",
                    name_bytes + goya_executable::D1_INT_VALUE_BYTES
                );
            }
            InteractionType::Bool => {
                let _ = writeln!(
                    out,
                    "        registerBytes += {}",
                    name_bytes + goya_executable::D1_BOOL_VALUE_BYTES
                );
            }
        }
        let _ = writeln!(out, "        guard registerBytes <= {} else {{ throw NeptuneTransitionError.registerLimit }}", goya_executable::D1_MAX_REGISTER_BYTES);
        index
    }
}

fn convert(
    expr: &Expression,
    state: &BTreeMap<String, usize>,
    inputs: &BTreeMap<String, usize>,
) -> Result<SwiftExpr, &'static str> {
    Ok(match &expr.operation {
        Operation::Constant(InteractionValue::Int(v)) => SwiftExpr::Int(*v),
        Operation::Constant(InteractionValue::Text(v)) => SwiftExpr::Text(v.clone()),
        Operation::Constant(InteractionValue::Bool(v)) => SwiftExpr::Bool(*v),
        Operation::State(key) => {
            SwiftExpr::State(*state.get(key).ok_or("unknown state key")?, expr.value_type)
        }
        Operation::Input(key) => SwiftExpr::Input(
            *inputs.get(key).ok_or("unknown input key")?,
            expr.value_type,
        ),
        Operation::CheckedAdd(left, right) => SwiftExpr::CheckedAdd(
            Box::new(convert(left, state, inputs)?),
            Box::new(convert(right, state, inputs)?),
        ),
    })
}

fn swift_type(ty: InteractionType) -> &'static str {
    match ty {
        InteractionType::Int => "Int64",
        InteractionType::Text => "String",
        InteractionType::Bool => "Bool",
    }
}

// Replicates Goya's D1 map_size accounting over this statically typed schema.
// Keys are never emitted as code: only their UTF-8 byte counts are used.
fn emit_snapshot_check(out: &mut String, owner: &str, label: &str, fields: &[Field]) {
    for field in fields
        .iter()
        .filter(|field| field.value_type == InteractionType::Text)
    {
        let _ = writeln!(out, "        guard {owner}.{}.utf8.count <= {} else {{ throw NeptuneTransitionError.textTooLarge }}", field.swift_name, goya_executable::D1_MAX_TEXT_BYTES);
    }
    let base = goya_executable::D1_SNAPSHOT_HEADER_BYTES
        + fields
            .iter()
            .map(|field| {
                goya_executable::D1_SNAPSHOT_ENTRY_BYTES
                    + field.source_key.len()
                    + match field.value_type {
                        InteractionType::Int => goya_executable::D1_INT_VALUE_BYTES,
                        InteractionType::Bool => goya_executable::D1_BOOL_VALUE_BYTES,
                        InteractionType::Text => 0,
                    }
            })
            .sum::<usize>();
    let _ = write!(out, "        let {label}Bytes = {base}");
    for field in fields
        .iter()
        .filter(|field| field.value_type == InteractionType::Text)
    {
        let _ = write!(out, " + {owner}.{}.utf8.count", field.swift_name);
    }
    out.push('\n');
    let _ = writeln!(
        out,
        "        guard {label}Bytes <= {} else {{ throw NeptuneTransitionError.snapshotTooLarge }}",
        goya_executable::D1_MAX_SNAPSHOT_BYTES
    );
}

/// Preview exactly one D1 transition. State field names are deterministic slots;
/// the returned metadata maps them to source keys for a future typed adapter.
pub fn preview(source: &str, module: &str) -> Result<Preview, crate::Diagnostic> {
    let mut transitions = transition::lower(source, module)?;
    if transitions.len() != 1 {
        return Err(crate::Diagnostic {
            code: "NPT-E2104",
            message: "transition preview requires exactly one D1 interaction".into(),
            range: None,
        });
    }
    let action = transitions.remove(0);
    let mut state_types = BTreeMap::new();
    for key in action.state_reads.iter().chain(&action.state_writes) {
        state_types.insert(key.name.clone(), key.value_type);
    }
    let input_types: BTreeMap<_, _> = action
        .inputs
        .iter()
        .map(|key| (key.name.clone(), key.value_type))
        .collect();
    let state_fields: Vec<_> = state_types
        .into_iter()
        .enumerate()
        .map(|(i, (key, ty))| Field {
            source_key: key,
            swift_name: format!("s{i}"),
            value_type: ty,
        })
        .collect();
    let input_fields: Vec<_> = input_types
        .into_iter()
        .enumerate()
        .map(|(i, (key, ty))| Field {
            source_key: key,
            swift_name: format!("i{i}"),
            value_type: ty,
        })
        .collect();
    let state: BTreeMap<_, _> = state_fields
        .iter()
        .enumerate()
        .map(|(i, field)| (field.source_key.clone(), i))
        .collect();
    let inputs: BTreeMap<_, _> = input_fields
        .iter()
        .enumerate()
        .map(|(i, field)| (field.source_key.clone(), i))
        .collect();
    let mut assignments = Vec::new();
    for assignment in &action.assignments {
        let slot = *state
            .get(&assignment.key)
            .ok_or_else(|| crate::Diagnostic {
                code: "NPT-E3102",
                message: "assignment has no state slot".into(),
                range: Some(action.source_range),
            })?;
        let value =
            convert(&assignment.value, &state, &inputs).map_err(|message| crate::Diagnostic {
                code: "NPT-E3102",
                message: message.into(),
                range: Some(action.source_range),
            })?;
        assignments.push((slot, value, assignment.value.value_type));
    }
    let mut out = String::from("enum NeptuneTransitionError: Error {\n    case arithmeticOverflow\n    case revisionOverflow\n    case textTooLarge\n    case snapshotTooLarge\n    case registerLimit\n}\n\nstruct NeptuneState {\n    var revision: UInt64\n");
    for field in &state_fields {
        let _ = writeln!(
            out,
            "    var {}: {}",
            field.swift_name,
            swift_type(field.value_type)
        );
    }
    out.push_str("}\n\nstruct NeptuneInput {\n");
    for field in &input_fields {
        let _ = writeln!(
            out,
            "    var {}: {}",
            field.swift_name,
            swift_type(field.value_type)
        );
    }
    out.push_str("}\n\nenum NeptuneTransition {\n    private static func checkedAdd(_ lhs: Int64, _ rhs: Int64) throws -> Int64 {\n        let (value, overflow) = lhs.addingReportingOverflow(rhs)\n        guard !overflow else { throw NeptuneTransitionError.arithmeticOverflow }\n        return value\n    }\n\n    static func apply(state: NeptuneState, input: NeptuneInput) throws -> NeptuneState {\n");
    emit_snapshot_check(&mut out, "state", "state", &state_fields);
    emit_snapshot_check(&mut out, "input", "input", &input_fields);
    let _ = writeln!(out, "        guard stateBytes + inputBytes <= {} else {{ throw NeptuneTransitionError.snapshotTooLarge }}", goya_executable::D1_MAX_SNAPSHOT_BYTES);
    out.push_str("        var registerBytes = 0\n");
    let mut next_register = 0usize;
    for (index, (_, expr, ty)) in assignments.iter().enumerate() {
        let register = expr.emit_register(&mut out, &mut next_register);
        let _ = writeln!(
            out,
            "        let value{index}: {} = r{register}",
            swift_type(*ty)
        );
    }
    out.push_str("        var next = state\n");
    for (index, (slot, _, _)) in assignments.iter().enumerate() {
        let _ = writeln!(out, "        next.s{slot} = value{index}");
    }
    emit_snapshot_check(&mut out, "next", "next", &state_fields);
    out.push_str("        let (revision, overflow) = state.revision.addingReportingOverflow(1)\n        guard !overflow else { throw NeptuneTransitionError.revisionOverflow }\n        next.revision = revision\n        return next\n    }\n}\n");
    Ok(Preview {
        swift: out,
        action: action.semantic_id,
        trigger: action.trigger_id,
        source_range: action.source_range,
        source_digest: action.source_digest,
        reference_program_hash: action.reference_program_hash,
        state_fields,
        input_fields,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    const SOURCE: &str = "@ontology app { @button plus { id: \"button.plus\" } @interaction increment { id: \"action.increment\"; trigger: button.plus.activate; class: D1; state { read count: int; write count: int; write previous: int; } input { amount: int; } set count = state.count + input.amount; set previous = state.count; } }";

    #[test]
    fn emits_typed_checked_snapshot_transition_deterministically() {
        let result = preview(SOURCE, "app/main.gscene").unwrap();
        assert_eq!(result, preview(SOURCE, "app/main.gscene").unwrap());
        assert_eq!(
            result
                .state_fields
                .iter()
                .map(|f| (&*f.source_key, &*f.swift_name))
                .collect::<Vec<_>>(),
            [("count", "s0"), ("previous", "s1")]
        );
        assert_eq!(result.input_fields[0].source_key, "amount");
        assert!(result.swift.contains("let r0: Int64 = state.s0"));
        assert!(result.swift.contains("let r1: Int64 = input.i0"));
        assert!(result
            .swift
            .contains("let r2: Int64 = try checkedAdd(r0, r1)"));
        assert!(result.swift.contains("let r3: Int64 = state.s0"));
        assert!(result.swift.contains("let value0: Int64 = r2"));
        assert!(result.swift.contains("let value1: Int64 = r3"));
        assert!(
            result.swift.find("let value1").unwrap()
                < result.swift.find("var next = state").unwrap()
        );
        assert!(result
            .swift
            .contains("next.s0 = value0\n        next.s1 = value1"));
        assert!(result
            .swift
            .contains("state.revision.addingReportingOverflow(1)"));
        assert!(SOURCE[result.source_range.start..result.source_range.end]
            .starts_with("@interaction increment"));
    }

    #[test]
    fn refuses_missing_interactions_and_preserves_signed_minimum() {
        assert!(preview(
            "@ontology x { @cell root { id: \"root\" text: \"Hi\" } }",
            "app/main.gscene"
        )
        .is_err());
        let source = "@ontology app { @button set { id: \"b\" } @interaction min { id: \"a\"; trigger: button.set.activate; class: D1; state { write count: int; } input { } set count = -9223372036854775808; } }";
        assert!(preview(source, "app/main.gscene")
            .unwrap()
            .swift
            .contains("let r0: Int64 = Int64.min"));
    }

    #[test]
    fn emits_typed_bool_and_escaped_text_without_source_identifiers() {
        let source = "@ontology app { @button set { id: \"b\" } @interaction save { id: \"a\"; trigger: button.set.activate; class: D1; state { write message: text; write enabled: bool; } input { } set message = \"hello\\(unsafe)\"; set enabled = true; } }";
        let result = preview(source, "app/main.gscene").unwrap();
        assert!(result
            .swift
            .contains("let r0: String = \"hello\\\\(unsafe)\""));
        assert!(result.swift.contains("let r1: Bool = true"));
        assert!(result
            .swift
            .contains("next.s1 = value0\n        next.s0 = value1"));
        assert!(!result.swift.contains("var message:"));
    }

    #[test]
    fn text_limits_use_utf8_bytes_and_reference_constants() {
        use goya_executable::{D1Snapshot, D1Value};
        let exact = "é".repeat(goya_executable::D1_MAX_TEXT_BYTES / 2);
        assert!(D1Snapshot::new(
            0,
            BTreeMap::from([("text".into(), D1Value::Text(exact.clone()))])
        )
        .is_ok());
        assert!(D1Snapshot::new(
            0,
            BTreeMap::from([("text".into(), D1Value::Text(format!("{exact}é")))])
        )
        .is_err());
        let source = "@ontology app { @button set { id: \"b\" } @interaction copy { id: \"a\"; trigger: button.set.activate; class: D1; state { read message: text; write message: text; } input { } set message = state.message; } }";
        let output = preview(source, "app/main.gscene").unwrap().swift;
        assert!(output.contains(&format!(
            "guard state.s0.utf8.count <= {}",
            goya_executable::D1_MAX_TEXT_BYTES
        )));
        assert!(output.contains(&format!(
            "guard next.s0.utf8.count <= {}",
            goya_executable::D1_MAX_TEXT_BYTES
        )));
        assert!(output.contains("let stateBytes = 23 + state.s0.utf8.count"));
        assert!(output.contains("registerBytes += 2 + r0.utf8.count"));
    }

    #[test]
    fn reference_enforces_register_and_result_snapshot_limits() {
        use goya_executable::{D1Snapshot, D1Value, InputSnapshot};
        fn fixture(writes: usize) -> String {
            let declarations: String = (0..writes).map(|i| format!("write o{i}: text; ")).collect();
            let assignments: String = (0..writes)
                .map(|i| format!("set o{i} = state.message; "))
                .collect();
            format!("@ontology app {{ @button set {{ id: \"b\" }} @interaction copy {{ id: \"a\"; trigger: button.set.activate; class: D1; state {{ read message: text; {declarations} }} input {{ }} {assignments} }} }}")
        }
        for (writes, text_len, expected) in [
            (16, 65536, "registers exceed the byte limit"),
            (17, 60000, "snapshot exceeds the byte limit"),
        ] {
            let source = fixture(writes);
            let scene = goya_lang::parse_strict(&source).unwrap().scene;
            let program = goya_lang::compile_d1_interactions(&scene)
                .unwrap()
                .remove(0);
            let mut values =
                BTreeMap::from([("message".to_string(), D1Value::Text("x".repeat(text_len)))]);
            for i in 0..writes {
                values.insert(format!("o{i}"), D1Value::Text(String::new()));
            }
            let error = program
                .execute(
                    &D1Snapshot::new(0, values).unwrap(),
                    &InputSnapshot::default(),
                )
                .unwrap_err();
            assert!(format!("{error:?}").contains(expected), "{error:?}");
            let swift = preview(&source, "app/main.gscene").unwrap().swift;
            assert!(swift.contains(&format!(
                "guard registerBytes <= {}",
                goya_executable::D1_MAX_REGISTER_BYTES
            )));
            let next = swift.find("let nextBytes = ").unwrap();
            let revision = swift
                .find("state.revision.addingReportingOverflow")
                .unwrap();
            assert!(next < revision);
        }
    }

    #[test]
    fn combined_snapshot_budget_is_checked_before_expression_execution() {
        use goya_executable::{D1Snapshot, D1Value, InputSnapshot};
        let reads: String = (0..9).map(|i| format!("read s{i}: text; ")).collect();
        let inputs: String = (0..9).map(|i| format!("i{i}: text; ")).collect();
        let writes: String = (0..18).map(|i| format!("write w{i}: text; ")).collect();
        let mut assignments = String::new();
        for i in 0..9 {
            assignments.push_str(&format!("set w{i} = state.s{i}; "));
        }
        for i in 0..9 {
            assignments.push_str(&format!("set w{} = input.i{i}; ", i + 9));
        }
        let source = format!("@ontology app {{ @button run {{ id: \"b\" }} @interaction copy {{ id: \"a\"; trigger: button.run.activate; class: D1; state {{ {reads}{writes} }} input {{ {inputs} }} {assignments} }} }}");
        let scene = goya_lang::parse_strict(&source).unwrap().scene;
        let reference = goya_lang::compile_d1_interactions(&scene)
            .unwrap()
            .remove(0);
        let mut state = BTreeMap::new();
        let mut input = BTreeMap::new();
        for i in 0..9 {
            state.insert(format!("s{i}"), D1Value::Text("x".repeat(60000)));
            input.insert(format!("i{i}"), D1Value::Text("x".repeat(60000)));
        }
        for i in 0..18 {
            state.insert(format!("w{i}"), D1Value::Text(String::new()));
        }
        let state = D1Snapshot::new(0, state).unwrap();
        let input = InputSnapshot::new(input).unwrap();
        let error = reference.execute(&state, &input).unwrap_err();
        assert!(format!("{error:?}").contains("snapshot exceeds the byte limit"));
        let swift = preview(&source, "app/main.gscene").unwrap().swift;
        assert!(
            swift.find("guard stateBytes + inputBytes").unwrap() < swift.find("let r0:").unwrap()
        );
    }
}
